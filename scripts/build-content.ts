// Runs before `next dev` and `next build` (see package.json `predev`/`prebuild`).
//
// Cloudflare Workers has no filesystem, so everything the app used to read from
// disk at request time is read HERE, in Node, and written into `lib/generated/`
// where the bundler picks it up:
//   - posts.json   the validated post index (`lib/content-index.ts`)
//   - og-fonts.ts  the .woff binaries Satori needs for the OG cards
// A malformed post throws here, so a bad post still fails the build.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { buildIndex } from "../lib/content-index";

const ROOT = process.cwd();
const OUT_DIR = join(ROOT, "lib", "generated");
const FONTS_DIR = join(ROOT, "fonts");

/** Export name in og-fonts.ts → file copied into `fonts/` by `fonts/init.mjs`. */
const OG_FONTS: Record<string, string> = {
  inter300: "inter-latin-300-normal.woff",
  inter600: "inter-latin-600-normal.woff",
  robotoMono400: "roboto-mono-latin-400-normal.woff",
};

function writePostIndex(): number {
  const posts = buildIndex();
  writeFileSync(join(OUT_DIR, "posts.json"), JSON.stringify(posts));
  return posts.length;
}

function writeOgFonts(): void {
  const exports = Object.entries(OG_FONTS).map(([name, file]) => {
    const base64 = readFileSync(join(FONTS_DIR, file)).toString("base64");
    return `export const ${name} = ${JSON.stringify(base64)};`;
  });
  const header =
    "// Generated by scripts/build-content.ts — do not edit. Base64 .woff data.\n";
  writeFileSync(join(OUT_DIR, "og-fonts.ts"), header + exports.join("\n") + "\n");
}

mkdirSync(OUT_DIR, { recursive: true });
const count = writePostIndex();
writeOgFonts();
console.log(`build-content: ${count} posts, ${Object.keys(OG_FONTS).length} OG fonts`);
